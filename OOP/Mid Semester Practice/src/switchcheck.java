public class switchcheck{
    public static void main(String[] args){
        int a = 10;
        switch(a){
            case 1:
                System.out.println("1 guys");
                break;
            case 2:
                System.out.println("2 guys");
                break;
            case 10:
                System.out.println("10 guys");
            case 'A':
                System.out.println("Character A");
        }
    }
}